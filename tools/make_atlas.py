#!/usr/bin/env python3
"""Generate fontdata.py: glyph coverage atlases for main.py.

This generator runs ONLY on the build machine (it needs Pillow and the
system DejaVu fonts). main.py itself is pure stdlib: it decodes the
atlases produced here and blits glyph bitmaps with its own rasterizer.

For every (face, size) the layout uses, each glyph is rendered once
with Pillow's ImageDraw.text at a known anchor (PAD, PAD); the cropped
bitmap plus its offset from that anchor and the font's advance width
are stored, so main.py can reproduce Pillow's text layout exactly:
blit at (pen_x + dx, y + dy), then pen_x += advance.
"""

import base64
import os
import sys
import zlib

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
FONT_DIR = "/usr/share/fonts/truetype/dejavu"

FACES = {
    "serif_bold": ("DejaVuSerif-Bold.ttf", [52]),
    "sans_bold": ("DejaVuSans-Bold.ttf", [15, 16, 20, 22, 24, 25, 31, 43]),
    "sans": ("DejaVuSans.ttf", [16, 19]),
}

PAD = 10


def charset():
    chars = set()
    # printable ASCII
    chars.update(chr(c) for c in range(0x20, 0x7F))
    # Latin-1 supplement printables (accents, currency, punctuation)
    chars.update(chr(c) for c in range(0xA1, 0x100))
    # typographic extras used by the headlines
    chars.update("‘’“”–—•…€★")
    # every character that literally appears in main.py's strings
    with open(os.path.join(REPO, "main.py"), encoding="utf-8") as fh:
        for ch in fh.read():
            if ord(ch) >= 0x20 and ch not in "\n\r\t":
                chars.add(ch)
    return sorted(chars)


def render_glyph(font, ch):
    """Return (advance, dx, dy, w, h, bitmap_bytes) for one glyph."""
    advance = font.getlength(ch)
    side = font.size * 3 + 2 * PAD
    img = Image.new("L", (side, side), 0)
    draw = ImageDraw.Draw(img)
    draw.text((PAD, PAD), ch, font=font, fill=255)
    bbox = img.getbbox()
    if bbox is None:
        return (advance, 0, 0, 0, 0, b"")
    crop = img.crop(bbox)
    return (advance, bbox[0] - PAD, bbox[1] - PAD,
            crop.size[0], crop.size[1], crop.tobytes())


def main():
    chars = charset()
    data = {}
    for face, (filename, sizes) in FACES.items():
        path = os.path.join(FONT_DIR, filename)
        data[face] = {}
        for size in sizes:
            font = ImageFont.truetype(path, size)
            ascent, descent = font.getmetrics()
            blob = bytearray()
            glyphs = {}
            for ch in chars:
                adv, dx, dy, w, h, bits = render_glyph(font, ch)
                glyphs[ch] = (round(adv, 3), dx, dy, w, h, len(blob), len(bits))
                blob += bits
            packed = base64.b64encode(zlib.compress(bytes(blob), 9)).decode("ascii")
            data[face][size] = {
                "ascent": ascent,
                "descent": descent,
                "blob": packed,
                "glyphs": glyphs,
            }
            print(f"{face} {size}: {len(chars)} glyphs, "
                  f"raw {len(blob)} bytes, packed {len(packed)} chars")

    out = os.path.join(REPO, "fontdata.py")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write('"""Glyph atlases for main.py -- generated by '
                 'tools/make_atlas.py.\n\n'
                 'Coverage bitmaps rendered from the DejaVu fonts '
                 '(Bitstream Vera / DejaVu\nlicense, free for any use) '
                 'with Pillow. DATA[face][size] holds the font metrics\n'
                 'and, per character, (advance, dx, dy, w, h, offset, '
                 'length) into the\nzlib+base64 blob of concatenated '
                 'glyph bitmaps.\n"""\n\n')
        fh.write("DATA = ")
        fh.write(repr(data))
        fh.write("\n")
    print(f"wrote {out} ({os.path.getsize(out)} bytes)")


if __name__ == "__main__":
    sys.exit(main())
